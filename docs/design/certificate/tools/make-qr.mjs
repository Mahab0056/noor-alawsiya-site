// Writes mock/qr.js: the QR matrix for the sample verify URL, made with the repo's own dependency (qrcode-generator, lib/qr.ts).
// Run: node docs/design/certificate/tools/make-qr.mjs   (needs the repo's node_modules, or NODE_PATH pointing at one)
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(process.env.CERT_NODE_MODULES ? path.join(process.env.CERT_NODE_MODULES, 'x.js') : path.join(here, '../../../../package.json'));
const qrcode = require('qrcode-generator');

const urls = ['https://noor-alawsiya.com/c/00EXAMP1'];
const out = {};
for (const url of urls) {
  const qr = qrcode(0, 'M'); // smallest version that fits, error correction M (15%), as lib/qr.ts
  qr.addData(url);
  qr.make();
  const n = qr.getModuleCount();
  const rows = [];
  for (let r = 0; r < n; r++) {
    let row = '';
    for (let c = 0; c < n; c++) row += qr.isDark(r, c) ? '1' : '0';
    rows.push(row);
  }
  out[url] = rows;
  console.log(url, `${n}x${n} modules (version ${(n - 17) / 4})`);
}
writeFileSync(path.join(here, '../mock/qr.js'), `/* generated by tools/make-qr.mjs */\nwindow.CERT_QR = ${JSON.stringify(out, null, 1)};\n`);
